"""Scene screenshot parity: +MC frames against Java client frames.

The Java reference frames are not generated by this repository, and this test
does not launch a Java client. Point `PLUSMC_JAVA_SCREENSHOTS` at a directory
of Java screenshots with the same filenames as the +MC preview output. Without
that directory the comparator's own identity/shift checks still run, then the
test exits 77 so a machine without references never fabricates a score.
"""

from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

from PIL import Image

TOOLS = Path(__file__).resolve().parent.parent / "tools"
sys.path.insert(0, str(TOOLS))

from scene_compare import compare_images, matching_frames  # noqa: E402


def self_test() -> None:
    with tempfile.TemporaryDirectory(prefix="plusmc-scene-") as tmp:
        root = Path(tmp)
        base = Image.new("RGB", (32, 18), (80, 120, 160))
        base.save(root / "same.png")
        compare = compare_images(root / "same.png", root / "same.png")
        assert compare["similarity"] == 1.0 and compare["exact"] == 32 * 18
        moved = Image.new("RGB", (32, 18), (80, 120, 160))
        moved.putpixel((0, 0), (255, 0, 0))
        moved.save(root / "moved.png")
        compare = compare_images(root / "same.png", root / "moved.png")
        assert compare["exact"] == 32 * 18 - 1
        assert 0.99 < compare["similarity"] < 1.0


def main() -> int:
    self_test()
    repo = Path(__file__).resolve().parent.parent
    plusmc = repo / "premium-server" / "playtest"
    reference = Path(os.environ.get("PLUSMC_JAVA_SCREENSHOTS",
                                   repo / "data" / "vanilla" / "java_screenshots"))
    pairs = matching_frames(plusmc, reference) if reference.is_dir() else []
    if not pairs:
        print("skip: no Java reference screenshots; comparator self-test passed")
        return 77
    worst = 1.0
    for plusmc_path, java_path in pairs:
        result = compare_images(plusmc_path, java_path)
        print(f"{result['file']}: similarity {result['similarity']:.4%}; "
              f"exact {result['exact_ratio']:.2%}; MAE {result['mae']:.2f}")
        worst = min(worst, result["similarity"])
    if worst < 0.85:
        raise AssertionError(f"worst scene similarity {worst:.2%} is below 85%")
    print(f"ok: {len(pairs)} scene frames; worst similarity {worst:.4%}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        sys.exit(1)
