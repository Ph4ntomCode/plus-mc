"""Generates the 26.3 -> 26.2/26.1.2 block-state id maps.

The canonical server keeps a 26.3 world.  A 26.2 or 26.1 client has its own
built-in block-state registry, so the chunk palette cannot carry 26.3 ids.  The
two registries are almost entirely the same *states* under different numbers:
90.6% of 26.3's states exist byte-for-byte (same block name and properties) in
26.2, and 83.6% in 26.1.2.  This tool maps those by name/properties, not by id.

States introduced in 26.3 are mapped to a close older state so a chunk still
encodes instead of falling back to void:

  * a state of a block that exists in the target version -> that block's
    default state;
  * a missing slab/stairs/wall/fence/gate/button/plate/door/trapdoor/sign/
    carpet/pane -> the base block's default state;
  * air/cave_air/void_air -> the target air state;
  * water/lava -> the target fluid state;
  * anything else -> the target stone default state.

Usage:
    gen_block_translation.py SOURCE_26_3_BLOCKS_JSON TARGET_26_2_BLOCKS_JSON \
        TARGET_26_1_2_BLOCKS_JSON OUT_HEADER
"""

import json
import sys


def canonical_props(props):
    if not props:
        return ""
    return ",".join(f"{k}={props[k]}" for k in sorted(props))


def load(path):
    report = json.load(open(path))
    by_key = {}
    by_name = {}
    for name, block in report.items():
        states = block["states"]
        default = next((s for s in states if s.get("default")), states[0])
        by_name[name] = int(default["id"])
        for state in states:
            key = (name, canonical_props(state.get("properties")))
            by_key[key] = int(state["id"])
    return by_key, by_name


def fallback(name, props, target_names, air, water, lava, stone):
    if name in ("minecraft:air", "minecraft:cave_air", "minecraft:void_air"):
        return air
    if name == "minecraft:water":
        return water
    if name == "minecraft:lava":
        return lava
    if name in target_names:
        return target_names[name]
    suffixes = (
        "_slab", "_stairs", "_wall", "_fence_gate", "_fence", "_button",
        "_pressure_plate", "_door", "_trapdoor", "_sign", "_hanging_sign",
        "_carpet", "_pane",
    )
    for suffix in suffixes:
        if name.endswith(suffix):
            base = name[:-len(suffix)]
            if base in target_names:
                return target_names[base]
    return stone


def emit_array(name, values):
    out = [f"inline constexpr int32_t {name}[] = {{"]
    for i in range(0, len(values), 16):
        row = ", ".join(str(v) for v in values[i:i + 16])
        out.append(f"    {row},")
    out.append("};")
    return out


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        return 2
    source_path, target_262_path, target_2612_path, out_path = sys.argv[1:]
    source, _ = load(source_path)
    target_262, names_262 = load(target_262_path)
    target_2612, names_2612 = load(target_2612_path)

    ids = sorted(source.values())
    if ids != list(range(len(ids))):
        print("26.3 ids are not contiguous")
        return 1
    id_to_key = {sid: key for key, sid in source.items()}

    def map_for(target, target_names):
        air = target.get(("minecraft:air", ""), 0)
        water = target.get(("minecraft:water", ""), air)
        lava = target.get(("minecraft:lava", ""), air)
        stone = target.get(("minecraft:stone", ""), air)
        out = []
        exact = fallback_count = 0
        missing_names = {}
        for sid in ids:
            key = id_to_key[sid]
            if key in target:
                out.append(target[key])
                exact += 1
                continue
            mapped = fallback(key[0], key[1], target_names, air, water, lava, stone)
            out.append(mapped)
            fallback_count += 1
            missing_names[key[0]] = missing_names.get(key[0], 0) + 1
        print(f"{out_path}: {exact} exact, {fallback_count} fallback, "
              f"{len(missing_names)} block names missing")
        return out, missing_names

    map_262, missing_262 = map_for(target_262, names_262)
    map_2612, missing_2612 = map_for(target_2612, names_2612)

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// clang-format off",
        "//",
        "// 26.3 -> 26.2 / 26.1.2 block-state network-id maps. Generated by",
        "// tools/gen_block_translation.py from each version's own",
        "// reports/blocks.json; do not hand-edit.",
        "//",
        "// The array is indexed by the canonical 26.3 id (0..35722) and stores",
        "// the id the target client expects. States introduced after the target",
        "// release map to a close older state (see the generator).",
        "//",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace mc::translation::t0 {",
        f"inline constexpr int32_t kCanonicalBlockStateCount = {len(ids)};",
        "",
    ]
    lines += emit_array("kCanonicalTo262", map_262)
    lines += [""]
    lines += emit_array("kCanonicalTo2612", map_2612)
    lines += [
        "",
        "} // namespace mc::translation::t0",
        "",
    ]
    open(out_path, "w").write("\n".join(lines))
    print(f"wrote {out_path} ({len(ids)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
