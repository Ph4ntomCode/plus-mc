"""Generates ``src/world/living_entity_table.h`` — every *living* entity type.

``data/vanilla/26.3/entity_types.tsv`` is the game's own dump (a Java probe
against the server jar; see ``tools/gen_entity_types.py``): one row per
``EntityType`` that ``DefaultAttributes`` has a supplier for, i.e. every living
entity. ``tools/gen_mob_table.py`` drops three of them — the player, the armour
stand and the 26.3 mannequin — because they have no AI and no spawn egg.

The *living-entity registry* is still the full set, and the Phase-4 Tier-C
ledger measures it: the engine names all 93 types (dimensions, category,
attributes) here, while ``mob_table.h`` is the 90-row subset it simulates. The
three non-mobs are carried so a reader can see the whole registry in one place
and so the ledger can tell "carried but not simulated" from "missing".

Usage:
    gen_living_entity_table.py [--tsv TSV] [--out HEADER]
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_TSV = ROOT / "data" / "vanilla" / "26.3" / "entity_types.tsv"
DEFAULT_OUT = ROOT / "src" / "world" / "living_entity_table.h"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tsv", type=pathlib.Path, default=DEFAULT_TSV)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    if not args.tsv.is_file():
        print(f"no entity-types dump at {args.tsv}", file=sys.stderr)
        return 1

    columns = args.tsv.read_text().splitlines()
    header = columns[0].split("\t")
    index = {name: i for i, name in enumerate(header)}
    rows = []
    for line in columns[1:]:
        if not line.strip():
            continue
        fields = line.split("\t")
        rows.append({
            "id": int(fields[index["id"]]),
            "name": fields[index["name"]],
            "category": fields[index["category"]],
            "width": float(fields[index["width"]]),
            "height": float(fields[index["height"]]),
            "fire_immune": fields[index["fire_immune"]] == "true",
            "max_health": float(fields[index["max_health"]]),
            "movement_speed": float(fields[index["movement_speed"]]),
            "has_attack_damage": fields[index["has_attack_damage"]] == "true",
            "attack_damage": float(fields[index["attack_damage"]]),
            "armor": float(fields[index["armor"]]),
            "follow_range": float(fields[index["follow_range"]]),
            "attack_knockback": float(fields[index["attack_knockback"]]),
            "knockback_resistance": float(fields[index["knockback_resistance"]]),
            "jump_strength": float(fields[index["jump_strength"]]),
            "safe_fall_distance": float(fields[index["safe_fall_distance"]]),
        })
    rows.sort(key=lambda r: r["name"])

    def cstr(text: str) -> str:
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = []
    a = out.append
    a("// SPDX-License-Identifier: GPL-3.0-or-later")
    a("// Generated by tools/gen_living_entity_table.py — do not edit by hand.")
    a("//")
    a(f"// Every living entity type the 26.3 server registers ({len(rows)}), from the")
    a("// game's own probe (data/vanilla/26.3/entity_types.tsv). `mob_table.h` is")
    a("// the subset WITH AI this engine simulates; the player, the armour stand and")
    a("// the mannequin have attributes and dimensions but no AI, so they are named")
    a("// here and deliberately not simulated (see docs/PHASE4.md).")
    a("// clang-format off")
    a("#pragma once")
    a("")
    a("#include <cstdint>")
    a("")
    a("namespace mc::world {")
    a("")
    a("struct LivingEntityType {")
    a("  uint32_t id;              // protocol / BuiltInRegistries.ENTITY_TYPE id")
    a("  const char* name;")
    a("  const char* category;     // MobCategory.getSerializedName()")
    a("  float width, height;")
    a("  bool fire_immune;")
    a("  float max_health, movement_speed;")
    a("  bool has_attack_damage;")
    a("  float attack_damage, armor, follow_range;")
    a("  float attack_knockback, knockback_resistance, jump_strength, safe_fall_distance;")
    a("};")
    a("")
    a(f"inline constexpr LivingEntityType kLivingEntityTypes[{len(rows)}] = {{")
    for r in rows:
        a(f"    {{{r['id']}, {cstr(r['name'])}, {cstr(r['category'])}, "
          f"{r['width']}f, {r['height']}f, {'true' if r['fire_immune'] else 'false'}, "
          f"{r['max_health']}f, {r['movement_speed']}f, "
          f"{'true' if r['has_attack_damage'] else 'false'}, {r['attack_damage']}f, "
          f"{r['armor']}f, {r['follow_range']}f, {r['attack_knockback']}f, "
          f"{r['knockback_resistance']}f, {r['jump_strength']}f, "
          f"{r['safe_fall_distance']}f}},")
    a("};")
    a("")
    a("}  // namespace mc::world")
    a("// clang-format on")
    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out} ({len(rows)} living entity types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
