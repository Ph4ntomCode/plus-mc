"""Generates src/world/default_block_states.h: each 26.2 block's *default* state.

Why this exists: placing a block means choosing one of that block's states, and
the wire id alone does not say which. Picking "the first state of that block in
the table" is wrong whenever a property is ordered true-before-false or when the
first state is not the vanilla default — a chest went down as
`waterlogged=true` (so a placed chest rendered full of water), chests never
paired, and leaves/stairs/gates picked arbitrary variants.

Vanilla's own data-generator report (reports/blocks.json, BlockListReport)
marks exactly one state per block with `"default": true` — the state
`BlockStateDefinition` reports as `Block.defaultBlockState()`, i.e. what
`Block.getStateForPlacement` starts from and what vanilla writes when a block
changes without properties. Generate that report with:

    java -DbundlerMainClass=net.minecraft.data.Main -jar server-boot.jar \\
         --reports --output /tmp/mc_reports

Usage:
    gen_default_states.py BLOCKS_JSON BLOCK_STATES_HEADER OUT_HEADER

The generated (name, props, id) triples are validated against
src/world/block_states.h (the full state table with the network ids): every
default must be a state that table already knows, at the same id.
"""

import json
import re
import sys


def canonical_props(props):
    """Sorted k=v, comma joined — the key form the encoder builds."""
    if not props:
        return ""
    return ",".join(f"{k}={props[k]}" for k in sorted(props))


def load_full_table(header_path):
    """Parses src/world/block_states.h back into {(name, props): id}."""
    text = open(header_path).read()
    body = text.split("kBlockStates[]", 1)[1].split("};", 1)[0]
    pairs = re.findall(r'\{"([^"]+)", "([^"]*)", (-?\d+)\}', body)
    return {(n, p): int(i) for n, p, i in pairs}


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    blocks_json, states_header, out_path = sys.argv[1:]

    report = json.load(open(blocks_json))
    full = load_full_table(states_header)

    defaults = {}
    for name, blk in sorted(report.items()):
        found = [st for st in blk["states"] if st.get("default")]
        if not found:
            # A block with no state (or a report without the marker) is not
            # placeable-by-default; skip it rather than guess.
            continue
        if len(found) > 1:
            print(f"{name} claims {len(found)} default states; refusing to guess")
            return 1
        st = found[0]
        defaults[name] = (canonical_props(st.get("properties")), int(st["id"]))

    # Every default must agree with the full state table (same name+props+id);
    # a mismatch would mean the two reports came from different versions.
    mismatches = []
    for name, (props, sid) in sorted(defaults.items()):
        got = full.get((name, props))
        if got != sid:
            mismatches.append((name, props, sid, got))
    if mismatches:
        print(f"{len(mismatches)} default-state mismatch(es) vs the state table:")
        for m in mismatches[:20]:
            print("  ", m)
        return 1
    print(f"validated {len(defaults)} default states against {len(full)} known states")

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// clang-format off",
        "//",
        "// The *default* state of every 26.2 block (the state vanilla's",
        "// Block.defaultBlockState() reports), generated by",
        "// tools/gen_default_states.py from the 26.2 server jar's own data-generator",
        "// report (reports/blocks.json, BlockListReport), which marks one state of",
        "// each block with \"default\": true. Placement starts from these, then",
        "// applies the properties placement computes (chest type from the",
        "// neighbours, waterlogged from the fluid at the position, ...).",
        "//",
        "// Validated against src/world/block_states.h: every entry is a known",
        f"// state at a known id. Regenerate, don't hand-edit.",
        "//",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace mc::world {",
        "struct GeneratedDefaultBlockState {",
        '  const char* name;   // "minecraft:chest"',
        '  const char* props;  // canonical sorted k=v,k=v string ("" if none)',
        "  int32_t id;         // clientbound network state id",
        "};",
        "inline constexpr GeneratedDefaultBlockState kDefaultBlockStates[] = {",
    ]
    for name, (props, sid) in sorted(defaults.items()):
        lines.append(f'    {{"{name}", "{props}", {sid}}},')
    lines += [
        "};",
        f"inline constexpr int kDefaultBlockStateCount = {len(defaults)};",
        "",
        "} // namespace mc::world",
        "",
    ]
    open(out_path, "w").write("\n".join(lines))
    print(f"wrote {out_path} ({len(defaults)} blocks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
