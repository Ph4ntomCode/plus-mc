"""Generates `src/world/worldgen_biome_table.h` from the probe's parameter dump.

The overworld biome source is a `Climate.ParameterList`: the `minecraft:overworld`
multi-noise preset's parameter points, each a `Climate.ParameterPoint` of seven
quantized intervals plus the biome it names. `MultiNoiseBiomeSource.getNoiseBiome`
quantizes a climate sample (`Climate.target`) and searches that list for the
nearest point; the biome stage reproduces exactly that, so the table has to be
the game's own list, in the game's own order.

Hand-transcribing `OverworldBiomeBuilder` into a second implementation would be
a second chance to get a boundary wrong (the builder emits ~7600 points). Instead
`tools/gen_worldgen_dump.py` reads the list out of the game's registry
(`biome_parameters.tsv`, one row per point) and this tool transcribes *that*
into the header — the same generated-table pattern as `worldgen_table.h`, with
the game as the source of truth rather than a re-derivation.

Rows are checked against the advertised `worldgen/biome` registry listing, so a
biome the client was told about but the table lacks (or vice versa) is a
generation failure, not a silent wrong answer.

Usage:
    gen_biome_parameter_table.py [--tsv FILE] [--registry FILE] [--header FILE]

e.g.
    gen_biome_parameter_table.py \\
        --tsv tests/fixtures/worldgen/biome_parameters.tsv \\
        --registry data/vanilla/26.2/clientconfig/registries/worldgen_biome.txt \\
        --header src/world/worldgen_biome_table.h
"""

import argparse
import pathlib
import sys

_HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/gen_biome_parameter_table.py — do not edit by hand.
//
// The `minecraft:overworld` multi-noise biome parameter list: the search space
// `MultiNoiseBiomeSource` selects from, in the preset's own order (`index` in
// the dump is that order). Each row is one `Climate.ParameterPoint`: six
// quantized `Parameter` intervals — temperature, humidity, continentalness,
// erosion, depth, weirdness — and the point's offset, plus the biome it names.
// The C++ side compares a quantized climate sample against these longs, so the
// table carries the game's own arithmetic (`Climate.quantizeCoord`), not a
// re-derivation of it.
//
// The probe's dump also records, for two seed-42 chunks, which biome the game's
// own `getNoiseBiome` answers per quart cell and whether a linear scan over this
// list agrees (`biomes_seed42_c*_*.tsv`, `biome_meta.tsv`); `worldgen_biome.cpp`
// searches a vanilla-shaped RTree instead, and the worldgen test pins both.
//
// Regenerate with:
//   tools/gen_worldgen_dump.py ... (writes tests/fixtures/worldgen/biome_parameters.tsv)
//   tools/gen_biome_parameter_table.py
// clang-format off
#pragma once

#include <cstdint>

namespace mc::world {

// One `Climate.ParameterPoint.parameterSpace()` entry: the six climate
// coordinates in `Climate.TargetPoint`'s order, plus the point's offset as a
// point interval (`offset` is zero everywhere in this preset, but `fitness`
// squares it). Both bounds are quantized longs, as the game stores them.
struct WgBiomeParameter {
  int64_t min[6];
  int64_t max[6];
  int64_t offset;
  const char* biome;
};

inline constexpr WgBiomeParameter kWgBiomeParameters[COUNT] = {
"""


def read_parameters(tsv: pathlib.Path):
    """(index, min[6], max[6], offset, biome) rows from the probe's dump."""
    rows = []
    lines = tsv.read_text().splitlines()
    for line in lines:
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 15:
            raise SystemExit(f"{tsv}: expected 15 fields, got {len(fields)}: {line!r}")
        index = int(fields[0])
        if index != len(rows):
            raise SystemExit(f"{tsv}: out-of-order index {index} at row {len(rows)}")
        values = [int(v) for v in fields[1:14]]
        parameters = [(values[2 * d], values[2 * d + 1]) for d in range(6)]
        for d, (lo, hi) in enumerate(parameters):
            if lo > hi:
                raise SystemExit(f"{tsv}: row {index}: dimension {d} has {lo} > {hi}")
        rows.append((index, parameters, values[12], fields[14]))
    if not rows:
        raise SystemExit(f"{tsv}: no parameter rows")
    return rows


def registry_names(path: pathlib.Path) -> set:
    return {line.strip() for line in path.read_text().splitlines() if line.strip()}


def emit(rows) -> str:
    lines = [_HEADER.replace("COUNT", str(len(rows)))]
    for _, parameters, offset, biome in rows:
        minimum = ", ".join(str(lo) for lo, _ in parameters)
        maximum = ", ".join(str(hi) for _, hi in parameters)
        lines.append(f'    {{{{{minimum}}}, {{{maximum}}}, {offset}, "{biome}"}},')
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace mc::world")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tsv", type=pathlib.Path,
                        default=pathlib.Path("tests/fixtures/worldgen/biome_parameters.tsv"),
                        help="the probe's parameter dump")
    parser.add_argument("--registry", type=pathlib.Path,
                        default=pathlib.Path(
                            "data/vanilla/26.2/clientconfig/registries/worldgen_biome.txt"),
                        help="the advertised worldgen/biome order")
    parser.add_argument("--header", type=pathlib.Path,
                        default=pathlib.Path("src/world/worldgen_biome_table.h"),
                        help="output header")
    args = parser.parse_args()

    if not args.tsv.is_file():
        print(f"no parameter dump at {args.tsv}", file=sys.stderr)
        return 1
    rows = read_parameters(args.tsv)

    if args.registry.is_file():
        advertised = registry_names(args.registry)
        used = {biome for _, _, _, biome in rows}
        missing = sorted(advertised - used)
        extra = sorted(used - advertised)
        if extra:
            print(f"biomes absent from {args.registry}: {extra}", file=sys.stderr)
            return 1
        # Not every advertised biome needs a parameter row (the preset leaves
        # some to other dimensions), but the overworld must be able to name
        # every one it does use; `extra` is the fatal direction.
        if missing:
            print(f"note: {len(missing)} advertised biomes unused by the preset "
                  f"(e.g. {missing[:3]})")
    else:
        print(f"warning: no registry listing at {args.registry}; skipping the cross-check",
              file=sys.stderr)

    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(emit(rows))
    print(f"wrote {args.header} ({len(rows)} parameter points, "
          f"{len({biome for _, _, _, biome in rows})} distinct biomes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
