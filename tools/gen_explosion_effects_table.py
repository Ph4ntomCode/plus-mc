"""Generate src/world/explosion_effects_table.h: the explode packet's registry ids.

`ClientboundExplodePacket` names its particle, its sound and its block particles
by *network registry id*:

    ParticleOptions          ByteBufCodecs.registry(Registries.PARTICLE_TYPE)
    Holder<SoundEvent>       ByteBufCodecs.holderRegistry(Registries.SOUND_EVENT)
    WeightedList<...>        ExplosionParticleInfo.STREAM_CODEC per entry

Both registries are built in code (`ParticleTypes` and `SoundEvents` register
into `BuiltInRegistries`), so their protocol ids are registration order — which
is not alphabetical, not documented, and shifts whenever a release inserts a
type. Counting the registrations by hand across `SoundEvents`' static fields
(which call per-variant helpers: cat, chicken, cow, pig, wolf and the goat horn)
is exactly the transcription this tool exists to remove.

The source is the server's own data-generator report, which writes a
`protocol_id` for every entry of every built-in registry:

    java -DbundlerMainClass=net.minecraft.data.Main \
         -jar build/_dl/boot/server-boot.jar --reports
    # -> build/_dl/boot/generated/reports/registries.json

`Level.explode`'s defaults, which one explosion that destroys blocks uses, are
`ParticleTypes.EXPLOSION` for a small blast and `EXPLOSION_EMITTER` for a large
one (`ServerExplosion.isSmall` = `radius < 2.0`), `SoundEvents.GENERIC_EXPLODE`
and `DEFAULT_EXPLOSION_BLOCK_PARTICLES` = POOF at 0.5 scaling, SMOKE at 1.0.

Usage:
    tools/gen_explosion_effects_table.py [--reports PATH] [--out PATH]
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

PARTICLE_ANCHORS = [
    ("kParticleExplosionEmitter", "minecraft:explosion_emitter", "ParticleTypes.EXPLOSION_EMITTER"),
    ("kParticleExplosion", "minecraft:explosion", "ParticleTypes.EXPLOSION"),
    ("kParticlePoof", "minecraft:poof", "ParticleTypes.POOF (DEFAULT_EXPLOSION_BLOCK_PARTICLES)"),
    ("kParticleSmoke", "minecraft:smoke", "ParticleTypes.SMOKE (DEFAULT_EXPLOSION_BLOCK_PARTICLES)"),
]
SOUND_ANCHOR = ("kSoundGenericExplode", "minecraft:entity.generic.explode",
                "SoundEvents.GENERIC_EXPLODE")


def protocol_id(report: dict, registry: str, name: str) -> int:
    entries = report[registry]["entries"]
    if name not in entries:
        raise SystemExit(f"{registry}: no {name} in the report")
    entry = entries[name]
    if "protocol_id" not in entry:
        raise SystemExit(f"{registry}/{name}: the entry has no protocol_id")
    return int(entry["protocol_id"])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports",
                        default=str(REPO / "build" / "_dl" / "boot" / "generated" / "reports"
                                    / "registries.json"))
    parser.add_argument("--out", default=str(REPO / "src" / "world"
                                             / "explosion_effects_table.h"))
    args = parser.parse_args()

    report = json.loads(Path(args.reports).read_text())
    particle_count = len(report["minecraft:particle_type"]["entries"])
    sound_count = len(report["minecraft:sound_event"]["entries"])

    particles = [(const, protocol_id(report, "minecraft:particle_type", name),
                  name, comment) for const, name, comment in PARTICLE_ANCHORS]
    sound = (SOUND_ANCHOR[0], protocol_id(report, "minecraft:sound_event", SOUND_ANCHOR[1]),
             SOUND_ANCHOR[1], SOUND_ANCHOR[2])
    ids = [value for _, value, _, _ in particles] + [sound[1]]
    if len(set(ids)) != len(ids):
        raise SystemExit(f"the anchors share an id: {ids}")

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/gen_explosion_effects_table.py -- do not edit by hand.",
        "//",
        "// The clientbound explode packet names a particle, a sound and a list of",
        "// block particles by their network registry ids: the particle ids are",
        "// positions in `BuiltInRegistries.PARTICLE_TYPE`, the sound id a position in",
        "// `BuiltInRegistries.SOUND_EVENT` (ByteBufCodecs.registry). Both registries",
        "// are built in code, so the ids are registration order -- read here from the",
        f"// 26.2 server's own `--reports` dump: {particle_count} particle types and",
        f"// {sound_count} sound events. `Level.explode`'s defaults, which one",
        "// destroying blast uses (ServerExplosion.isSmall = radius < 2.0 for the",
        "// particle, DEFAULT_EXPLOSION_BLOCK_PARTICLES = POOF 0.5x then SMOKE 1.0x),",
        "// are what the anchors below are.",
        "// The id comments below run past the column limit.",
        "// clang-format off",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace mc::world {",
        "",
    ]
    for const, value, name, comment in particles:
        lines.append(f"inline constexpr uint32_t {const} = {value}; // {name} -- {comment}")
    lines += [
        f"inline constexpr uint32_t {sound[0]} = {sound[1]}; // {sound[2]} -- {sound[3]}",
        "// clang-format on",
        "",
        "} // namespace mc::world",
        "",
    ]
    out = Path(args.out)
    out.write_text("\n".join(lines))
    print(f"{out}: particle ids "
          + ", ".join(f"{name.split(':')[1]}={value}" for _, value, name, _ in particles)
          + f"; {sound[2]}={sound[1]} (of {particle_count} particle types, "
          f"{sound_count} sound events, {Path(args.reports).name})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
