// Concrete registry lookups for the chunk encoder (world/chunk.h interfaces).
//
// Milestone A shipped a minimal hand table for the flat fixture; milestone B
// replaces it with the *complete* 26.2 registry (src/world/block_states.h,
// generated from the vanilla jar's own data-generator report, 32366 states).
// The ids are the clientbound network state ids (palette values / global
// container entries a vanilla 26.2 client expects). The observed table below
// remains as the byte-verified stepping stone the generator validates
// against, and the encode fixtures still pin the milestone-A ground truth.
#pragma once

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <utility>
#include <vector>

#include "world/chunk.h"

namespace mc::world {

// Block-state table backed by a fixed list of (state, id) pairs. Linear scan
// lookup is fine for the small milestone-A/observed tables; the full 32k-entry
// registry uses a generated hash map behind the same interface.
class StaticBlockStateTable final : public BlockStateTable {
public:
  StaticBlockStateTable(std::vector<std::pair<BlockStateKey, int32_t>> states)
      : states_(std::move(states)) {}
  std::optional<int32_t> lookup(const BlockStateKey& key) const override;
  // The underlying (state, id) pairs, in table order (for table merging).
  const std::vector<std::pair<BlockStateKey, int32_t>>& entries() const {
    return states_;
  }

private:
  std::vector<std::pair<BlockStateKey, int32_t>> states_;
};

// The milestone-A block table (states present in the flat-world fixture).
// Returns a reference to a process-lifetime singleton.
const BlockStateTable& milestone_a_block_states();

// The observed block table (src/world/observed_block_states.h, generated by
// tools/map_states.py from a live vanilla 26.2 overworld capture): pairs
// whose ids are byte-verified clientbound ground truth. Kept for the encode
// fixtures; the runtime encoder uses full_block_states().
const BlockStateTable& observed_block_states();

// The complete 26.2 block-state table (src/world/block_states.h, generated
// by tools/gen_block_registry.py from the vanilla jar's data-generator
// report): every state of every vanilla block with its exact network id.
// Hash-backed for O(1) lookup at 32k entries. Returns a reference to a
// process-lifetime singleton.
const BlockStateTable& full_block_states();

// The state behind a network id, for readers holding an id rather than a key
// (the WASM host's world_get_block). Nullopt for an id the table does not
// contain. Process-lifetime and O(1), built once beside the forward table.
std::optional<BlockStateKey> block_state_by_id(int32_t id);

// A block's vanilla default state: what `Block.defaultBlockState()` reports,
// i.e. the state placement starts from before applying the properties
// placement itself computes (chest type from the neighbours, waterlogged from
// the fluid at the position, facing from the player's look).
struct DefaultBlockState {
  BlockStateKey key;
  int32_t id = 0;
};

// The vanilla default state of a block (src/world/default_block_states.h,
// generated by tools/gen_default_states.py from the vanilla jar's own
// data-generator report, which marks one state of each block as `default`).
// `name` may be given with or without the `minecraft:` namespace. Returns
// nullopt for a name the registry does not know.
std::optional<DefaultBlockState> default_block_state(std::string_view name);

// Biome table resolving registry entry names to the wire ids the client was
// given during configuration. `names` must be the advertised worldgen/biome
// registry order (clientconfig/registries/worldgen_biome.txt); the lookup is
// the entry's index, exactly how the client interprets palette values.
class NameListBiomeTable final : public BiomeNameTable {
public:
  explicit NameListBiomeTable(std::vector<std::string> names) : names_(std::move(names)) {
    index_.reserve(names_.size() * 2);
    for (size_t i = 0; i < names_.size(); ++i)
      index_.emplace(names_[i], static_cast<int32_t>(i));
  }
  std::optional<int32_t> lookup(const std::string& name) const override;
  size_t registry_size() const override {
    return names_.size();
  }

private:
  std::vector<std::string> names_;
  mutable std::unordered_map<std::string, int32_t> index_;
};

} // namespace mc::world
