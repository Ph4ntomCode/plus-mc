//
// Every biome's spawn list and spawn costs (795 spawner entries and
// 5 spawn-cost entries over 66 biomes, generated — do not
// hand-edit), flattened out of the vanilla 26.2 worldgen biome data pack by
// tools/gen_biome_spawn_table.py. This is the data `NaturalSpawner` picks
// a spawn from (Phase 4 milestone C).
//
//   * `kBiomeSpawns` is sorted by (biome, category), and within a category it
//     keeps the JSON's own order — `WeightedList` does not care about order,
//     so keeping it is what makes a row-by-row diff against the data pack
//     possible. `kBiomeSpawnRanges` is the per-biome slice of it.
//   * All eight `MobCategory`s are carried, including the water ones this
//     engine has no mob for: the *runtime* skips entries whose type the mob
//     table cannot create (world/mob_table.h) and renormalizes the weights of
//     the rest, so a spawn list is weighted over what can actually spawn.
//     207 of 795 entries (53 biomes) name a mob
//     this engine has today; the rest become reachable as the table grows.
//   * `kBiomeSpawnCosts` is `MobSpawnSettings.MobSpawnCost`, which only two
//     biomes set in 26.2 (soul_sand_valley, warped_forest). A biome with no
//     cost is absent, which is how `getMobSpawnCost` answers null.
//
// There is one entry per (biome, category) even when the list is empty, so
// the range table answers "what may spawn in this biome" in one lookup.
//
// Regenerate with tools/gen_biome_spawn_table.py.
